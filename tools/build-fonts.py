#!/usr/bin/env python3
"""Subset the OFL fonts to the characters actually used and embed them.

Scans index.html, final-draft.html and src/*.js for characters, subsets each
font with fontTools, writes WOFF2 files to assets/fonts/ and a fonts.css
that embeds them as base64 data URIs (so file:// opening works everywhere).

Source fonts come from npm packages (`npm install` in the repo root installs
them as devDependencies):
  @expo-google-fonts/noto-sans-tc, noto-serif-tc, lxgw-wenkai-tc, ibm-plex-mono

Usage:  python3 tools/build-fonts.py [--src node_modules]
"""
import argparse
import base64
import glob
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FONTS = [
    # family,     weight, package,          file
    ("AZ Sans", 400, "noto-sans-tc", "400Regular/NotoSansTC_400Regular.ttf"),
    ("AZ Sans", 500, "noto-sans-tc", "500Medium/NotoSansTC_500Medium.ttf"),
    ("AZ Sans", 700, "noto-sans-tc", "700Bold/NotoSansTC_700Bold.ttf"),
    ("AZ Serif", 600, "noto-serif-tc", "600SemiBold/NotoSerifTC_600SemiBold.ttf"),
    ("AZ Serif", 700, "noto-serif-tc", "700Bold/NotoSerifTC_700Bold.ttf"),
    ("AZ Kai", 400, "lxgw-wenkai-tc", "400Regular/LXGWWenKaiTC_400Regular.ttf"),
    ("AZ Kai", 700, "lxgw-wenkai-tc", "700Bold/LXGWWenKaiTC_700Bold.ttf"),
    ("AZ Mono", 400, "ibm-plex-mono", "400Regular/IBMPlexMono_400Regular.ttf"),
    ("AZ Mono", 500, "ibm-plex-mono", "500Medium/IBMPlexMono_500Medium.ttf"),
]

SCAN = ["index.html", "final-draft.html", "src/*.js"]


def used_chars():
    chars = set(chr(c) for c in range(0x20, 0x7F))  # printable ASCII always
    chars |= set("　、。，．：；？！「」『』（）《》〈〉・—–…→←↑↓≥≤×○●％／～＋－＝｜·")
    for pat in SCAN:
        for f in glob.glob(os.path.join(ROOT, pat)):
            with open(f, encoding="utf-8") as fh:
                chars |= set(fh.read())
    return {c for c in chars if ord(c) >= 0x20}


def subset_font(path, text):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    font = TTFont(path)
    sub = subset.Subsetter(options=opts)
    sub.populate(text=text)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(ROOT, "node_modules"))
    args = ap.parse_args()
    text = "".join(sorted(used_chars()))
    out_dir = os.path.join(ROOT, "assets", "fonts")
    os.makedirs(out_dir, exist_ok=True)
    css = ["/* Generated by tools/build-fonts.py — do not edit. Fonts: SIL Open Font License 1.1 */"]
    total = 0
    for fam, wt, pkg, rel in FONTS:
        src = os.path.join(args.src, "@expo-google-fonts", pkg, rel)
        if not os.path.exists(src):
            sys.exit(f"missing font: {src}\nrun `npm install` first")
        data = subset_font(src, text)
        name = f"{fam.replace(' ', '')}-{wt}.woff2"
        with open(os.path.join(out_dir, name), "wb") as fh:
            fh.write(data)
        b64 = base64.b64encode(data).decode("ascii")
        css.append(
            f'@font-face{{font-family:"{fam}";font-weight:{wt};font-style:normal;font-display:block;'
            f'src:url(data:font/woff2;base64,{b64}) format("woff2");}}'
        )
        total += len(data)
        print(f"{name:24s} {len(data)/1024:8.1f} KB")
    with open(os.path.join(out_dir, "fonts.css"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(css) + "\n")
    with open(os.path.join(out_dir, "charset.txt"), "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"{len(text)} characters · total {total/1024:.0f} KB woff2")


if __name__ == "__main__":
    main()
